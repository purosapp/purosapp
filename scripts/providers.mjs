import fs from 'node:fs'
import path from 'node:path'
import process from 'node:process'
import { spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { installSelfContainedFfmpeg } from './build-ffmpeg.mjs'
import { runBuildSteps, validateManifest } from '../provider-sdk/tooling/manifest.mjs'

export { runBuildSteps, validateManifest }

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const providersRoot = path.join(repoRoot, 'providers')
const generatedRegistryPath = path.join(repoRoot, 'electron', 'main', 'providers', 'generated.ts')
const generatedRuntimePath = path.join(repoRoot, 'electron', 'generated-provider-runtime.ts')
const generatedBuilderPath = path.join(repoRoot, 'build', 'providers.generated.json')
const coreFfmpegPath = path.join(repoRoot, 'build', 'audio', 'ffmpeg')

function parseArguments(argv) {
  const modeArg = argv.find((arg) => arg.startsWith('--mode='))
  const mode = modeArg?.slice('--mode='.length) ?? (process.env.NODE_ENV === 'production' ? 'release' : 'development')
  if (!['development', 'test', 'release'].includes(mode)) throw new Error(`Unsupported provider generation mode: ${mode}`)
  return { mode, skipBuild: argv.includes('--skip-build') }
}

function readBaseBuilderConfig() {
  const source = fs.readFileSync(path.join(repoRoot, 'electron-builder.json5'), 'utf8')
  return JSON.parse(source.replace(/^\s*\/\/.*$/gm, ''))
}

export function discoverProviders() {
  if (!fs.existsSync(providersRoot)) return []
  return fs.readdirSync(providersRoot, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => {
      const root = path.join(providersRoot, entry.name)
      const manifestPath = path.join(root, 'provider.manifest.json')
      if (!fs.existsSync(manifestPath)) return null
      const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'))
      validateManifest(manifest, entry.name)
      const entryPath = path.join(root, 'src', 'index.ts')
      if (!fs.existsSync(entryPath)) throw new Error(`Provider ${manifest.id} is missing src/index.ts`)
      return { directoryName: entry.name, root, manifest }
    })
    .filter(Boolean)
    .sort((left, right) => left.manifest.id.localeCompare(right.manifest.id))
}

function selectProviders(discovered, mode) {
  const rawSelection = process.env.PUROS_PROVIDERS?.trim()
  const hasExample = discovered.some(({ manifest }) => manifest.id === 'example')
  const selection = rawSelection || (mode === 'release' ? 'none' : hasExample ? 'example' : 'none')
  if (selection === 'none') return []
  const requested = selection === 'all'
    ? discovered
      .map(({ manifest }) => manifest.id)
      .filter((id) => mode !== 'release' || id !== 'example')
    : selection.split(',').map((id) => id.trim()).filter(Boolean)
  if (mode === 'release' && requested.includes('example')) throw new Error('The example provider is excluded from release builds')
  const requestedSet = new Set(requested)
  const known = new Set(discovered.map(({ manifest }) => manifest.id))
  const unknown = [...requestedSet].filter((id) => !known.has(id))
  if (unknown.length > 0) throw new Error(`Unknown provider selection: ${unknown.join(', ')}`)
  return discovered.filter(({ manifest }) => requestedSet.has(manifest.id) && !(mode === 'release' && manifest.id === 'example'))
}

function prepareCoreFfmpeg() {
  if (process.platform !== 'darwin') return
  // Packages ship only the pinned, self-contained LGPL build (never a Homebrew
  // or PATH binary), so local DSD playback and live radio work on a clean Mac.
  installSelfContainedFfmpeg(path.dirname(coreFfmpegPath))
  const packagedProbe = spawnSync(coreFfmpegPath, ['-version'], { timeout: 3_000, stdio: 'ignore' })
  if (packagedProbe.status !== 0) throw new Error('The copied core ffmpeg executable cannot start')
}

function writeGeneratedRegistry(selected) {
  const definitions = selected.map((provider) => `  {
    directoryName: ${JSON.stringify(provider.directoryName)},
    manifest: ${JSON.stringify(provider.manifest, null, 2)} as ProviderManifestV1,
  }`)
  const source = [
    '// Generated by scripts/providers.mjs. Do not edit.',
    ...(selected.length > 0 ? ["import type { ProviderManifestV1 } from '../../../src/provider-api/v1'"] : []),
    "import type { GeneratedProviderDefinitionV1 } from './loader'",
    '',
    `export const generatedProviders: GeneratedProviderDefinitionV1[] = [\n${definitions.join(',\n')}\n]`,
    '',
  ].join('\n')
  fs.mkdirSync(path.dirname(generatedRegistryPath), { recursive: true })
  fs.writeFileSync(generatedRegistryPath, source)
}

function writeGeneratedRuntime(selected) {
  const imports = selected.map((provider, index) => {
    const relative = path.relative(path.dirname(generatedRuntimePath), path.join(provider.root, 'src', 'index.ts')).replaceAll(path.sep, '/')
    return `import plugin${index} from ${JSON.stringify(relative.startsWith('.') ? relative : `./${relative}`)}`
  })
  const source = [
    '// Generated by scripts/providers.mjs. Do not edit.',
    "import type { ProviderPluginV1 } from '../src/provider-api/v1'",
    ...imports,
    '',
    `export const generatedRuntimePlugins: Record<string, ProviderPluginV1> = {\n${selected.map((provider, index) => `  ${JSON.stringify(provider.manifest.id)}: plugin${index},`).join('\n')}\n}`,
    '',
  ].join('\n')
  fs.mkdirSync(path.dirname(generatedRuntimePath), { recursive: true })
  fs.writeFileSync(generatedRuntimePath, source)
}

function writeGeneratedBuilderConfig(selected) {
  const config = readBaseBuilderConfig()
  const resources = [...(config.extraResources ?? [])]
  const binaries = [...(config.mac?.binaries ?? [])]
  if (process.platform === 'darwin') {
    resources.push({ from: 'build/audio', to: 'audio', filter: ['ffmpeg', 'FFMPEG-COPYING.LGPLv2.1', 'SOXR-COPYING.LGPL', 'FFMPEG-BUILD-INFO.json'] })
    binaries.push('Contents/Resources/audio/ffmpeg')
  }
  for (const provider of selected) {
    for (const resource of provider.manifest.build?.extraResources ?? []) {
      resources.push({
        from: path.relative(repoRoot, path.resolve(provider.root, resource.from)).replaceAll(path.sep, '/'),
        to: resource.to,
        ...(resource.filter ? { filter: resource.filter } : {}),
      })
    }
    for (const binary of provider.manifest.build?.binaries ?? []) {
      binaries.push(`Contents/Resources/${binary}`)
    }
  }
  config.extraResources = resources
  config.mac = { ...config.mac, binaries }
  fs.mkdirSync(path.dirname(generatedBuilderPath), { recursive: true })
  fs.writeFileSync(generatedBuilderPath, `${JSON.stringify(config, null, 2)}\n`)
}

export function generateProviders({ mode, skipBuild } = parseArguments(process.argv.slice(2))) {
  const discovered = discoverProviders()
  const selected = selectProviders(discovered, mode)
  if (!skipBuild) {
    prepareCoreFfmpeg()
    runBuildSteps(selected)
  }
  writeGeneratedRegistry(selected)
  writeGeneratedRuntime(selected)
  writeGeneratedBuilderConfig(selected)
  return { mode, discovered: discovered.map(({ manifest }) => manifest.id), selected: selected.map(({ manifest }) => manifest.id) }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const result = generateProviders()
  console.log(`Provider generation (${result.mode}): ${result.selected.join(', ') || 'none'}`)
}
